  const originalText = new WeakMap();
  const originalAttributes = new WeakMap();
  let current = "zh-CN";

  function normalizeLocale(value) {
    if (typeof value !== "string") return null;
    const normalized = value.trim().toLowerCase();
    if (normalized === "en" || normalized.startsWith("en-")) return "en";
    if (normalized === "zh" || normalized.startsWith("zh-")) return "zh-CN";
    return null;
  }

  function detectLocale(stored, browserLanguage) {
    return normalizeLocale(stored) || normalizeLocale(browserLanguage) || "zh-CN";
  }

  function interpolate(value, variables) {
    if (!variables || typeof variables !== "object") return value;
    return value.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) => (
      Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : match
    ));
  }

  function translate(value, variables) {
    const source = String(value ?? "");
    if (current !== "en") return interpolate(source, variables);
    const whitespace = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const leading = whitespace?.[1] || "";
    const core = whitespace?.[2] ?? source;
    const trailing = whitespace?.[3] || "";
    const direct = english[core];
    if (direct !== undefined) return `${leading}${interpolate(direct, variables)}${trailing}`;
    for (const [pattern, formatter] of patterns) {
      if (pattern.test(core)) return `${leading}${interpolate(core.replace(pattern, formatter), variables)}${trailing}`;
    }
    return interpolate(source, variables);
  }

  function locale() {
    return current;
  }

  function intlLocale() {
    return current === "en" ? "en-US" : "zh-CN";
  }

  function translateTextNode(node, register = false) {
    if (!node || node.nodeType !== 3) return;
    const parent = node.parentElement;
    if (parent?.closest("script, style, [data-i18n-skip]")) return;
    let existing = originalText.get(node);
    if (existing === undefined && !register) return;
    if (existing === undefined) {
      existing = node.data;
      originalText.set(node, existing);
    }
    if (current === "zh-CN") {
      if (node.data !== existing) node.data = existing;
      return;
    }
    const source = existing;
    const translated = translate(source);
    if (translated === source) return;
    if (node.data !== translated) node.data = translated;
  }

  function translateAttribute(element, name, register = false) {
    if (!element?.hasAttribute?.(name) || element.closest("[data-i18n-skip]")) return;
    let values = originalAttributes.get(element);
    if (!values) {
      values = new Map();
      originalAttributes.set(element, values);
    }
    let existing = values.get(name);
    if (existing === undefined && !register) return;
    if (existing === undefined) {
      existing = element.getAttribute(name);
      values.set(name, existing);
    }
    if (current === "zh-CN") {
      if (element.getAttribute(name) !== existing) element.setAttribute(name, existing);
      return;
    }
    const source = existing;
    const translated = translate(source);
    if (translated === source) return;
    if (element.getAttribute(name) !== translated) element.setAttribute(name, translated);
  }

  function translateElement(element, register = false) {
    if (!element || element.nodeType !== 1) return;
    ["aria-label", "title", "placeholder", "value"].forEach((name) => translateAttribute(element, name, register));
  }

  function translateDOM(root = globalScope.document, { register = false } = {}) {
    if (!root || typeof globalScope.NodeFilter === "undefined") return;
    if (root.nodeType === 3) {
      translateTextNode(root, register);
      return;
    }
    if (root.nodeType === 1) translateElement(root, register);
    const documentValue = root.ownerDocument || root;
    const walker = documentValue.createTreeWalker(
      root,
      globalScope.NodeFilter.SHOW_ELEMENT | globalScope.NodeFilter.SHOW_TEXT,
    );
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === 3) translateTextNode(node, register);
      else translateElement(node, register);
      node = walker.nextNode();
    }
  }

  function registerDOM(root) {
    translateDOM(root, { register: true });
  }

  function syncControls() {
    if (!globalScope.document) return;
    globalScope.document.documentElement.lang = current;
    globalScope.document.querySelectorAll("[data-language-toggle]").forEach((control) => {
      const englishActive = current === "en";
      control.setAttribute("aria-pressed", englishActive ? "true" : "false");
      control.setAttribute("aria-label", englishActive ? "Switch to Chinese" : "切换到英文");
      const value = control.querySelector("[data-language-value]");
      if (value) value.textContent = englishActive ? "EN" : "中";
      const caption = control.querySelector("[data-language-caption]");
      if (caption) caption.textContent = englishActive ? "Language" : "语言";
      const label = control.querySelector("[data-language-label]");
      if (label) label.textContent = englishActive ? "English" : "中文";
    });
  }

  function setLocale(next, { persist = true, announce = true } = {}) {
    const normalized = normalizeLocale(next) || "zh-CN";
    if (!SUPPORTED.has(normalized)) return current;
    const changed = normalized !== current;
    current = normalized;
    if (persist) {
      try {
        globalScope.localStorage?.setItem(STORAGE_KEY, current);
      } catch (_error) {
        // Language switching still works when storage is unavailable.
      }
    }
    syncControls();
    translateDOM(globalScope.document);
    if (changed && announce && typeof globalScope.CustomEvent === "function") {
      globalScope.dispatchEvent(new globalScope.CustomEvent("branch-radar:languagechange", {
        detail: { locale: current },
      }));
    }
    return current;
  }

  function toggleLocale() {
    return setLocale(current === "en" ? "zh-CN" : "en");
  }

  function initialize() {
    if (!globalScope.document) return current;
    let stored = null;
    try {
      stored = globalScope.localStorage?.getItem(STORAGE_KEY);
    } catch (_error) {
      stored = null;
    }
    current = detectLocale(stored, globalScope.navigator?.language);
    syncControls();
    registerDOM(globalScope.document);
    globalScope.document.querySelectorAll("[data-language-toggle]").forEach((control) => {
      if (control.dataset.languageBound === "true") return;
      control.dataset.languageBound = "true";
      control.addEventListener("click", toggleLocale);
    });
    return current;
  }

